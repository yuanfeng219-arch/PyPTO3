      return {name: name.split('(')[0], id: name.match(/\((.*?)\)/)[1], taskId: String(first.args.taskId), start: Math.min(...workers.map(e=>e.ts)), end: Math.max(...workers.map(e=>e.ts+e.dur)), fanin: first.args['fanin-hint'], fanout: first.args['fanout-hint'], event: first, dispatch: scheduled?.args['dispatch-time-us'] ?? null, kernel: workers.length === 1 ? first.args['kernel-duration-us'] : null, setup: workers.length === 1 ? first.args.local_setup_us : null, cores: workers.map(e=>({start:e.ts, end:e.ts+e.dur,lane:lanes.get(e.tid)||String(e.tid),eventId:e.id})), rootHash: first.args.rootHash ?? null, callOpMagic: first.args.callOpMagic ?? null, leafHash: first.args.leafHash ?? null};
