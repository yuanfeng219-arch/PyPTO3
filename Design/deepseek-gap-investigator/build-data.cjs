function snippet(file, needle, before=3, after=12) {
  const lines = fs.readFileSync(path.join(base,file),'utf8').split('\n');
  const i = lines.findIndex(l=>l.includes(needle));
  if(i<0) throw Error(`Missing source ${needle}`);
  const start=Math.max(0,i-before);
  let end=i+after+1;
  if(lines[i].trimStart().startsWith('def ')) {
    const next=lines.findIndex((l,n)=>n>i&&l.startsWith('    @pl.function'));
    if(next>i)end=Math.min(end,next);
  }
  return {file,line:i+1,start:start+1,lines:lines.slice(start,end)};
}
